/* Demo sample: a small demoscene-style screen - rainbow logo, raster bars, a scroller and a
   3-voice tune on the Mockingboard - with the current temperature in Celle, fetched by the Apple II
   itself through FujiNet (N:HTTPS + JSON from open-meteo.com). C does the network part and
   prepares the screen; samples/demo_fx.s does everything that moves. The Apple II counterpart of
   the Atari, C64 and CPC kits' demos. Generated by Claude Code - see README.md (The demo).

   Lo-res graphics with 4 text lines (mixed mode), 40 x 40 blocks. The Apple II has no colour
   registers: every frame is drawn again into the hidden page and shown at the vertical blank.
     block rows 1-17    logo, three lines of the 3x5 font, a rainbow running down
     block rows 19-31   raster bars
     block rows 33-37   scroller in the same font, a rainbow running up
     text lines 20-23   info panel */
#include <stdio.h>
#include <string.h>
#include "fujinet-network.h"

#define URL "N1:HTTPS://api.open-meteo.com/v1/forecast?latitude=52.62&longitude=10.08&current=temperature_2m"

/* shared with demo_fx.s */
extern unsigned char fx_mask[20 * 40];  /* per text row: bit 0 top block, bit 1 bottom block = letter */
void fx_start(void);
unsigned char scroll_cols[3000];        /* the scroller text as font columns: bit 0 = top row */
unsigned int scroll_len;

/* 3x5 font, ASCII 32-95: 5 rows of 3 bits (bit 2 = left column). '*' = degree sign */
static const unsigned char big_font[64 * 5] = {
    0,0,0,0,0,  2,2,2,0,2,  5,5,0,0,0,  5,7,5,7,5,      /* space ! " # */
    3,6,2,3,6,  5,1,2,4,5,  2,5,2,5,3,  2,2,0,0,0,      /* $ % & ' */
    1,2,2,2,1,  4,2,2,2,4,  6,6,0,0,0,  0,2,7,2,0,      /* ( ) * + */
    0,0,0,2,4,  0,0,7,0,0,  0,0,0,0,2,  1,1,2,4,4,      /* , - . / */
    7,5,5,5,7,  2,6,2,2,7,  6,1,2,4,7,  6,1,2,1,6,      /* 0-3 */
    5,5,7,1,1,  7,4,6,1,6,  3,4,7,5,7,  7,1,2,2,2,      /* 4-7 */
    7,5,7,5,7,  7,5,7,1,6,  0,2,0,2,0,  0,2,0,2,4,      /* 8 9 : ; */
    1,2,4,2,1,  0,7,0,7,0,  4,2,1,2,4,  6,1,2,0,2,      /* < = > ? */
    2,5,5,4,3,  2,5,7,5,5,  6,5,6,5,6,  3,4,4,4,3,      /* @ A B C */
    6,5,5,5,6,  7,4,6,4,7,  7,4,6,4,4,  3,4,5,5,3,      /* D E F G */
    5,5,7,5,5,  7,2,2,2,7,  1,1,1,5,2,  5,5,6,5,5,      /* H I J K */
    4,4,4,4,7,  5,7,7,5,5,  6,5,5,5,5,  2,5,5,5,2,      /* L M N O */
    6,5,6,4,4,  2,5,5,6,3,  6,5,6,5,5,  3,4,2,1,6,      /* P Q R S */
    7,2,2,2,2,  5,5,5,5,7,  5,5,5,5,2,  5,5,7,7,5,      /* T U V W */
    5,5,2,5,5,  5,5,2,2,2,  7,1,2,4,7,  3,2,2,2,3,      /* X Y Z [ */
    4,4,2,1,1,  6,2,2,2,6,  2,5,0,0,0,  0,0,0,0,7       /* \ ] ^ _ */
};

/* columns of a character: 1 for the narrow ones (their middle column), 2 for space and the
   degree sign (its left two columns), else 3 */
static unsigned char big_width(char c)
{
    if (c == '.' || c == ':' || c == '!' || c == '\'' || c == ',' || c == ';')
        return 1;
    if (c == ' ' || c == '*')
        return 2;
    return 3;
}

static char temp[16];
static char line[48];

static void fetch_temperature(void)
{
    int16_t len;

    strcpy(temp, "??");
    network_init();
    if (network_open(URL, OPEN_MODE_HTTP_GET, OPEN_TRANS_NONE) != FN_ERR_OK)
        return;
    if (network_json_parse(URL) == FN_ERR_OK) {
        len = network_json_query(URL, "/current/temperature_2m", temp);
        if (len <= 0)
            strcpy(temp, "??");
    }
    network_close(URL);
    for (len = 0; temp[len]; ++len)
        if (!((temp[len] >= '0' && temp[len] <= '9') || temp[len] == '.' || temp[len] == '-')) {
            temp[len] = 0;
            break;
        }
    if (temp[0] == 0)
        strcpy(temp, "??");
}

static unsigned char upper(char c)
{
    if (c >= 'a' && c <= 'z')
        c -= 32;
    if ((unsigned char)c < 32 || (unsigned char)c > 95)
        c = ' ';
    return c;
}

/* one line of the big font into block rows row..row+4, centred, as letter bits in fx_mask */
static void big_line(unsigned char row, const char *s)
{
    unsigned char width = 0, x, y, n, w, bits, c;
    const char *t;
    const unsigned char *g;

    for (t = s; *t; ++t)                        /* in the logo a space is one column */
        width += (*t == ' ' ? 1 : big_width(upper(*t))) + 1;
    --width;
    x = width < 40 ? (40 - width) / 2 : 0;
    for (t = s; *t && x < 40; ++t) {
        c = upper(*t);
        w = c == ' ' ? 1 : big_width(c);
        g = big_font + (c - 32) * 5;
        for (n = 0; n < w && x + n < 40; ++n)
            for (y = 0; y < 5; ++y) {
                bits = g[y];
                if (w == 1 ? (bits & 2) : (bits & (4 >> n)))
                    fx_mask[((row + y) >> 1) * 40 + x + n] |= ((row + y) & 1) ? 2 : 1;
            }
        x += w + 1;
    }
}

/* text line: 0x80 | char = normal; inverse = upper case 0x00-0x3F. Both display pages. */
static const unsigned int text_row[4] = { 0x650, 0x6D0, 0x750, 0x7D0 };

static void text_line(unsigned char r, const char *s, unsigned char inverse)
{
    unsigned char x = (40 - strlen(s)) / 2;
    unsigned char *p1 = (unsigned char *)text_row[r - 20] + x;
    unsigned char *p2 = p1 + 0x400;
    unsigned char c;

    for (; *s; ++s) {
        c = inverse ? (upper(*s) & 0x3F) : (*s | 0x80);
        *p1++ = c;
        *p2++ = c;
    }
}

/* the scroller text as columns, one blank column after each character */
static void add(const char *s)
{
    unsigned char c, w, n, y, col;
    const unsigned char *g;

    for (; *s && scroll_len < sizeof scroll_cols - 4; ++s) {
        c = upper(*s);
        w = big_width(c);
        g = big_font + (c - 32) * 5;
        for (n = 0; n < w; ++n) {
            col = 0;
            for (y = 0; y < 5; ++y)
                if (w == 1 ? (g[y] & 2) : (g[y] & (4 >> n)))
                    col |= 1 << y;
            scroll_cols[scroll_len++] = col;
        }
        scroll_cols[scroll_len++] = 0;
    }
}

int main(void)
{
    unsigned char r;

    printf("Fetching the temperature in Celle\nthrough FujiNet...\n");
    fetch_temperature();

    memset(fx_mask, 0, sizeof fx_mask);
    big_line(1, "APPLE II");
    big_line(7, "+FUJINET");
    strcpy(line, "CELLE ");
    strcat(line, temp);
    strcat(line, "*C");
    big_line(13, line);

    for (r = 20; r < 24; ++r) {                 /* blank text lines on both pages */
        memset((unsigned char *)text_row[r - 20], 0xA0, 40);
        memset((unsigned char *)text_row[r - 20] + 0x400, 0xA0, 40);
    }
    text_line(20, "A small demo from the Apple II devkit", 0);
    strcpy(line, "Celle right now: ");
    strcat(line, temp);
    strcat(line, " C, via FujiNet");
    text_line(21, line, 0);
    text_line(22, "cc65, fujinet-lib, FujiNet Go Apple II", 0);
    text_line(23, "github.com/joergr72idb", 0);   /* inverse fringes too much in mixed mode */

    add("*** Hello from Celle! ***   The temperature here is ");
    add(temp);
    add(" C right now - the Apple II fetched it itself through FujiNet (N:HTTPS + JSON from "
        "open-meteo.com) ...   Music: three AY voices on the Mockingboard - lo-res graphics drawn "
        "again every frame into the hidden page ...   Get the toolchain: "
        "github.com/joergr72idb/development-kit-apple2-and-fujinet - kits for the Atari XL, "
        "the C64 and the CPC too ...   Greetings to the FujiNet team, the Atari-Club Celle and "
        "everyone at Classic Computing 2026 ...   Let's wrap!          ");

    fx_start();                                 /* never returns */
    return 0;
}
