/* Demo sample: a small demoscene-style screen - rainbow logo, raster bars, smooth scroller and a
   3-voice SID tune - with the current temperature in Celle, fetched by the C64 itself through
   FujiNet (N:HTTPS + JSON from open-meteo.com). C does the network part and fills the screen;
   samples/demo.s does everything that moves (raster interrupts, scroller, music).
   The C64 counterpart of the Atari kit's demo. Generated by Claude Code - see README.md (Samples).

   Screen (text rows, 8 raster lines each):
     0-7    logo, two lines of big letters made of quadrant characters: the letters are holes in
            black characters, so they show the background colour, which the raster interrupt
            changes every line (rainbow)
     8-11   raster bars
     12-19  info panel (blue)
     20-22  raster bars
     23     scroller: reverse characters (letters are holes again), rainbow behind them
     24     black */
#include <string.h>
#include <stdio.h>
#include "fujinet-network.h"

#define SCREEN  ((unsigned char *)0x0400)
#define COLRAM  ((unsigned char *)0xD800)

extern unsigned char scroll_buf[1024];
extern unsigned int scroll_len;
void demo_start(void);

/* cc65 stores these in PETSCII; the FujiNet converts device specs and queries from the C64 to ASCII
   itself (the bus's nativeTextToUnicode) - so they go out unchanged */
static const char url[] = "N1:HTTPS://api.open-meteo.com/v1/forecast?latitude=52.62&longitude=10.08&current=temperature_2m";
static const char query[] = "/current/temperature_2m";

static char temp[16];
static char line[41];

static void fetch_temperature(void)
{
    int16_t len;

    strcpy(temp, "??");
    if (network_open(url, OPEN_MODE_HTTP_GET, OPEN_TRANS_NONE) != FN_ERR_OK)
        return;
    if (network_json_parse(url) == FN_ERR_OK) {
        len = network_json_query(url, query, temp);
        if (len <= 0)
            strcpy(temp, "??");
    }
    network_close(url);
    /* the answer is ASCII: digits, '.', '-' - the same codes in PETSCII; drop anything else */
    for (len = 0; temp[len]; ++len)
        if (!((temp[len] >= '0' && temp[len] <= '9') || temp[len] == '.' || temp[len] == '-')) {
            temp[len] = 0;
            break;
        }
    if (temp[0] == 0)
        strcpy(temp, "??");
}

/* character (as cc65 stores it) -> screen code of the lower case charset */
static unsigned char scr(char c)
{
    if (c >= 'a' && c <= 'z')
        return c - 'a' + 1;
    if (c >= 'A' && c <= 'Z')
        return c - 'A' + 0x41;
    if (c == '@')
        return 0;
    if ((unsigned char)c >= 0x20 && (unsigned char)c < 0x40)
        return c;
    return 0x20;
}

/* panel line: centred, in one colour; inverse = $80 */
static void panel_line(unsigned char row, const char *s, unsigned char col, unsigned char inv)
{
    unsigned char x = (40 - strlen(s)) / 2;
    unsigned char *d = SCREEN + row * 40 + x;
    unsigned char *c = COLRAM + row * 40 + x;

    while (*s) {
        *d++ = scr(*s++) | inv;
        *c++ = col;
    }
}

/* ---- big letters: 5x7 pixel font, 2x2 pixels per character (quadrant graphics) ------------- */
static const char big_chars[] = "C64+FUJINETL0123578-.? *";       /* '*' = degree sign */
static const unsigned char big_font[][7] = {
    { 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E },  /* C */
    { 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E },  /* 6 */
    { 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 },  /* 4 */
    { 0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00 },  /* + */
    { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10 },  /* F */
    { 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E },  /* U */
    { 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C },  /* J */
    { 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E },  /* I */
    { 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11 },  /* N */
    { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F },  /* E */
    { 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04 },  /* T */
    { 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F },  /* L */
    { 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E },  /* 0 */
    { 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E },  /* 1 */
    { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F },  /* 2 */
    { 0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E },  /* 3 */
    { 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E },  /* 5 */
    { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 },  /* 7 */
    { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E },  /* 8 */
    { 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00 },  /* - */
    { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10 },  /* . */
    { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04 },  /* ? */
    { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 },  /* space */
    { 0x0C, 0x12, 0x12, 0x0C, 0x00, 0x00, 0x00 },  /* degree */
};
/* 9 is a turned 6 */
static const unsigned char big_nine[7] = { 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C };

/* character for the 2x2 pixel mask UL=8 UR=4 LL=2 LR=1 (checked against the character ROM) */
static const unsigned char quad[16] = {
    0x20, 0x6C, 0x7B, 0x62, 0x7C, 0xE1, 0xFF, 0xFE,
    0x7E, 0x7F, 0x61, 0xFC, 0xE2, 0xFB, 0xEC, 0xA0
};

static unsigned char bits[8][10];               /* 80 x 8 pixels, one logo line */

static const unsigned char *glyph(char c, unsigned char *w)
{
    const char *p;

    *w = 5;
    if (c == '9')
        return big_nine;
    if (c == '.' ) *w = 1;
    if (c == ' ' || c == '-') *w = 3;
    if (c == '*') *w = 4;
    if (c == 'I') *w = 3;
    p = strchr(big_chars, c);
    if (p == 0)
        p = strchr(big_chars, '?');
    return big_font[p - big_chars];
}

/* one line of big letters into text rows row..row+3; letters stay holes (background colour),
   the rest becomes black quadrant characters */
static void big_line(unsigned char row, const char *s)
{
    unsigned char x, y, w, n, m;
    unsigned char width = 0;
    const char *t;
    const unsigned char *g;
    unsigned char shift;

    for (t = s; *t; ++t) {
        glyph(*t, &w);
        width += w + 1;
    }
    --width;
    memset(bits, 0, sizeof bits);
    x = (80 - width) / 2;
    for (t = s; *t; ++t) {
        g = glyph(*t, &w);
        /* narrow glyphs use the left columns of their 5 - except I, which is centred */
        shift = (*t == 'I') ? 1 : 0;
        for (y = 0; y < 7; ++y)
            for (n = 0; n < w; ++n)
                if (g[y] & (0x10 >> (n + shift)))
                    bits[y][(x + n) >> 3] |= 0x80 >> ((x + n) & 7);
        x += w + 1;
    }
    for (y = 0; y < 4; ++y)
        for (x = 0; x < 40; ++x) {
            n = x * 2;
            m = 0;
            if (bits[y * 2][n >> 3] & (0x80 >> (n & 7)))         m |= 8;
            if (bits[y * 2][n >> 3] & (0x40 >> (n & 7)))         m |= 4;
            if (bits[y * 2 + 1][n >> 3] & (0x80 >> (n & 7)))     m |= 2;
            if (bits[y * 2 + 1][n >> 3] & (0x40 >> (n & 7)))     m |= 1;
            SCREEN[(row + y) * 40 + x] = quad[15 - m];
            COLRAM[(row + y) * 40 + x] = 0;
        }
}

static unsigned int add(unsigned int n, const char *s)
{
    while (*s)
        scroll_buf[n++] = scr(*s++) | 0x80;    /* reverse: the letter is a hole */
    return n;
}

int main(void)
{
    unsigned int n;

    printf("fetching the temperature in celle\nthrough fujinet...\n");
    fetch_temperature();

    memset(SCREEN, 0x20, 1000);
    memset(COLRAM, 14, 1000);
    *(unsigned char *)0xD018 = 0x17;            /* screen $0400, lower case charset */

    big_line(0, "C64+FUJINET");
    strcpy(line, "CELLE ");
    strcat(line, temp);
    strcat(line, "*C");
    big_line(4, line);

    panel_line(13, "A small demo from the C64 devkit", 1, 0);
    strcpy(line, "Celle right now: ");
    strcat(line, temp);
    strcat(line, " C");
    panel_line(15, line, 7, 0);
    panel_line(16, "live via FujiNet, N:HTTPS + JSON", 13, 0);
    panel_line(18, "cc65, fujinet-lib, VICE, FujiNet-PC", 15, 0);
    panel_line(19, " github.com/joergr72idb ", 3, 0x80);

    memset(SCREEN + 23 * 40, 0xA0, 40);         /* scroller row: black until the text arrives */
    memset(COLRAM + 23 * 40, 0, 40);

    n = add(0, "*** Hello from Celle! ***   The temperature here is ");
    n = add(n, temp);
    n = add(n, " C right now - the C64 fetched it itself through FujiNet "
        "(N:HTTPS + JSON from open-meteo.com) ...   "
        "Code: cc65 (C + ca65 assembler) and fujinet-lib, tested in VICE with the NetIEC "
        "bridge and FujiNet-PC ...   Music: three SID voices in the raster interrupt - "
        "raster bars and a rainbow behind holes in the characters - smooth scrolling "
        "with $D016 ...   Get the whole toolchain: "
        "github.com/joergr72idb/development-kit-c64-and-fujinet"
        " - kits for the Atari XL, the CPC + M4 and the Apple II too ...   "
        "More at github.com/joergr72idb: Retro Game Battle, Berlin Blues BBS, CPC Telnet, "
        "FujiNet Network CPC, Neon Grid ...   Greetings to the FujiNet team, the Atari-Club "
        "Celle and everyone at Classic Computing 2026 ...   Let's wrap!          ");
    scroll_len = n;

    demo_start();
    for (;;)                                    /* the rest happens in the interrupts */
        ;
}
