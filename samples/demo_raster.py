#!/usr/bin/env python3
"""Generates the raster routine of samples/demo (sdasz80 source on stdout): 201 scan lines of
exactly 64 microseconds each, unrolled. On the CPC every instruction takes a whole number of
"NOPs" (1 us), so the timing can be counted here instead of being measured.

Per line (table entry i, written in the horizontal blank before line i):
    inc b / outi  x4      pen select, colour, pen select, colour (Gate Array, port &7Fxx)
    exx ... exx           a piece of the scroller shift (LDI from HL' to DE'), 8 scan lines
                          of 80 bytes, row 22 of the screen, one byte to the left
    padding               to 64 us

    python3 demo_raster.py DELAY > demo_raster.s

DELAY: microseconds from the call to the first line's code (puts the colour writes into the
horizontal blank; found with screenshots)."""
import sys

LINES = 201
LINE_US = 64
SCROLL_ROW = 22
OUT_US = 4 * 6                      # 4 x (inc b 1 + outi 5)
EXX_US = 2

out = []
label = [0]


def emit(s):
    out.append("        " + s)


def pad(us):
    """exactly us microseconds, A is free"""
    if us >= 9:
        n = (us - 1) // 4           # ld a,#n (2) + n-1 taken loops (4) + last (3) = 4n+1
        label[0] += 1
        emit(f"ld      a, #{n}")
        out.append(f"p{label[0]}$:")
        emit("dec     a")
        emit(f"jr      nz, p{label[0]}$")
        us -= 4 * n + 1
    for _ in range(us):
        emit("nop")


def main():
    delay = int(sys.argv[1])
    # the copy, as a list of (microseconds, code)
    ops = []
    for k in range(8):
        ops += [(5, ["ldi"])] * 80
        if k < 7:                   # on to the next scan line of the row: +&800-80
            ops.append((11, ["ld      bc, #0x07B0", "add     hl, bc", "ex      de, hl",
                             "add     hl, bc", "ex      de, hl"]))
    print("; generated by samples/demo_raster.py - do not edit")
    print("        .module demo_raster")
    print("        .globl  _fx_tbl, scr_src, scr_dst")
    print("        .area   _CODE")
    print("raster::")
    out.clear()
    # fixed part: the delay, then the registers
    emit("di")                      # 1
    emit("exx")                     # 1
    emit("ld      hl, (scr_src)")   # 5
    emit("ld      de, (scr_dst)")   # 6
    emit("exx")                     # 1
    emit("ld      hl, #_fx_tbl")    # 3
    emit("ld      bc, #0x7F00")     # 3
    pad(delay - 20)
    budget = LINE_US - OUT_US - EXX_US
    for line in range(LINES):
        out.append(f"; line {line}")
        for _ in range(4):
            emit("inc     b")
            emit("outi")
        used = 0
        if ops:
            emit("exx")
            while ops and used + ops[0][0] <= budget:
                us, code = ops.pop(0)
                for c in code:
                    emit(c)
                used += us
            emit("exx")
            used += EXX_US
        pad(LINE_US - OUT_US - used)
    assert not ops, "the scroller copy did not fit"
    emit("ei")
    emit("ret")
    print("\n".join(out))


main()
