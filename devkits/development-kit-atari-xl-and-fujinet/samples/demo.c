/* Demo sample: a small demoscene-style screen - rainbow logo, raster bars, fine scroller and a
   POKEY tune - with the current temperature in Celle, fetched by the Atari itself through
   FujiNet (N:HTTPS + JSON from open-meteo.com). C does the network part and the texts;
   samples/demo.s does everything that moves (display list, DLIs, VBI, music).
   Generated by Claude Code from a single prompt - see README.md (Samples). */
#include <stdio.h>
#include <string.h>
#include "fujinet-network.h"

#define URL "N1:HTTPS://api.open-meteo.com/v1/forecast?latitude=52.62&longitude=10.08&current=temperature_2m"

extern unsigned char logo[40];          /* 2 lines of 20, ANTIC mode 7 */
extern unsigned char panel[320];        /* 8 lines of 40, ANTIC mode 2 */
extern unsigned char scroll_buf[1024];
extern unsigned int scroll_len;
void demo_start(void);

#define PAD 24                          /* the scroller line shows up to 24 characters */

static char temp[16];
static char line[41];

static void fetch_temperature(void)
{
    int16_t len;

    strcpy(temp, "??");
    if (network_open(URL, OPEN_MODE_HTTP_GET, OPEN_TRANS_NONE) != FN_ERR_OK)
        return;
    if (network_json_parse(URL) == FN_ERR_OK) {
        len = network_json_query(URL, "/current/temperature_2m", temp);
        if (len <= 0)
            strcpy(temp, "??");
    }
    network_close(URL);
}

/* ATASCII -> ANTIC screen code */
static unsigned char scr(unsigned char c)
{
    if (c < 32)
        return c + 64;
    if (c < 96)
        return c - 32;
    return c;
}

/* mode 2 line, centred; inverse = bit 7 */
static void panel_line(unsigned char row, const char *s, unsigned char inv)
{
    unsigned char *d = panel + row * 40 + (40 - strlen(s)) / 2;

    while (*s)
        *d++ = scr(*s++) | inv;
}

/* Mode 7 text (logo, scroller): 64 glyphs, bits 6-7 pick the colour register. Plain text uses
   colour 0 (the rainbow), '~' switches colour 1 (gold) on/off, '^' colour 3 (cyan). */
static unsigned int big(unsigned char *d, const char *s)
{
    unsigned char col = 0;
    unsigned int n = 0;
    char c;

    while ((c = *s++) != 0) {
        if (c == '~') {
            col = col == 0x40 ? 0 : 0x40;
            continue;
        }
        if (c == '^') {
            col = col == 0xC0 ? 0 : 0xC0;
            continue;
        }
        if (c >= 'a' && c <= 'z')
            c -= 32;
        d[n++] = (scr(c) & 0x3F) | col;
    }
    return n;
}

static void big_centred(unsigned char *d, const char *s)
{
    big(d + (20 - strlen(s)) / 2, s);
}

int main(void)
{
    unsigned int n;

    printf("Fetching the temperature in Celle\nthrough FujiNet...\n");
    fetch_temperature();

    big_centred(logo, "ATARI XL+FUJINET");
    strcpy(line, "CELLE ");
    strcat(line, temp);
    strcat(line, " C");
    big_centred(logo + 20, line);

    panel_line(1, "A small demo from the Atari devkit", 0);
    strcpy(line, "Celle right now: ");
    strcat(line, temp);
    strcat(line, " C");
    panel_line(3, line, 0);
    panel_line(4, "live via FujiNet, N:HTTPS + JSON", 0);
    panel_line(6, "cc65, fujinet-lib, atari800, FujiNet-PC", 0);
    panel_line(7, " github.com/joergr72idb ", 0x80);

    /* PAD blank characters before and after the text: at scroll_len the window shows only
       the trailing blanks, the same picture as at 0, so the VBI starts over there */
    n = PAD;
    n += big(scroll_buf + n, "*** ~HELLO FROM CELLE!~ ***   THE TEMPERATURE HERE IS ~");
    n += big(scroll_buf + n, temp);
    n += big(scroll_buf + n,
        " C~ RIGHT NOW - THE ATARI FETCHED IT ITSELF THROUGH FUJINET "
        "(N:HTTPS + JSON FROM OPEN-METEO.COM) ...   "
        "CODE: CC65 (C + CA65 ASSEMBLER) AND FUJINET-LIB, TESTED IN ATARI800 WITH NETSIO "
        "AND FUJINET-PC ...   MUSIC: FOUR POKEY VOICES IN THE VERTICAL BLANK - RASTER BARS "
        "BY DISPLAY LIST INTERRUPTS - FINE SCROLLING WITH HSCROL ...   "
        "GET THE WHOLE TOOLCHAIN: ^GITHUB.COM/JOERGR72IDB/DEVELOPMENT-KIT-ATARI-XL-AND-FUJINET^"
        " - KITS FOR THE C64, THE CPC + M4 AND THE APPLE II TOO ...   "
        "MORE AT ^GITHUB.COM/JOERGR72IDB^: RETRO GAME BATTLE, BERLIN BLUES BBS, CPC TELNET, "
        "FUJINET NETWORK CPC, NEON GRID ...   GREETINGS TO THE FUJINET TEAM, THE ATARI-CLUB "
        "CELLE AND EVERYONE AT CLASSIC COMPUTING 2026 ...   LET'S WRAP!   ");
    scroll_len = n;

    demo_start();
    for (;;)                            /* the rest happens in the interrupts */
        ;
}
