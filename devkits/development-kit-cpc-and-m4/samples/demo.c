/* Demo sample: a small demoscene-style screen - rainbow logo, raster bars, scroller and a
   3-voice AY tune - with the current temperature in Celle, fetched by the CPC itself through
   the M4 (HTTP + JSON from open-meteo.com). C does the network part and draws the screen;
   samples/demo_fx.s and the generated raster routine (samples/demo_raster.py) do everything
   that moves. The CPC counterpart of the Atari and C64 kits' demos. Generated by Claude Code -
   see README.md (Samples).

   Screen, mode 1 (scan lines):
     8-39     logo, two lines of letters 16x16 (the firmware font doubled) in pen 1, whose
              colour changes every line: rainbow
     40-79    raster bars (border and background)
     80-143   info panel: pen 2 background, pen 1 text in one colour per row
     144-175  raster bars
     176-183  scroller, pen 1 with a rainbow */
#include <stdio.h>
#include <string.h>
#include "cpc.h"
#include "m4.h"

/* the M4 has no HTTPS; open-meteo answers plain HTTP too */
#define URL "http://api.open-meteo.com/v1/forecast?latitude=52.62&longitude=10.08&current=temperature_2m"

extern unsigned char fx_font[96 * 8];
extern unsigned char fx_tbl[201 * 4];
void fx_init(void);
void fx_start(void);

char scroll_text[1024];
unsigned int scroll_len;

static unsigned char buf[1024];
static char temp[16];
static char line[41];

/* {"current_units":{...,"temperature_2m":"°C"},"current":{...,"temperature_2m":3.3}} */
static void fetch_temperature(void)
{
    unsigned int n;
    char *p;
    unsigned char i = 0;

    strcpy(temp, "??");
    if (m4_init() != 0)
        return;
    n = m4_http_get(URL, buf, sizeof buf - 1);
    buf[n] = 0;
    p = strstr((char *)buf, "\"current\":");
    if (p == 0)
        return;
    p = strstr(p, "\"temperature_2m\":");
    if (p == 0)
        return;
    p += 17;
    while (i < sizeof temp - 1 && ((*p >= '0' && *p <= '9') || *p == '.' || *p == '-'))
        temp[i++] = *p++;
    temp[i] = 0;
    if (i == 0)
        strcpy(temp, "??");
}

/* address of byte x (0-79) on scan line y (0-199) */
static unsigned char *scr(unsigned char x, unsigned char y)
{
    return (unsigned char *)(0xC000 + (y >> 3) * 80 + (y & 7) * 0x800 + x);
}

static const unsigned char degree[8] = { 0x38, 0x6C, 0x6C, 0x38, 0, 0, 0, 0 };

static const unsigned char *glyph(char c)
{
    if (c == '*')
        return degree;
    if (c < 32 || c > 127)
        c = ' ';
    return fx_font + (c - 32) * 8;
}

/* big letters: every font pixel 2x2, pen 1 on pen 0. Mode 1 byte: pixel n has pen bit 0 in
   bit 7-n and pen bit 1 in bit 3-n. */
static void big_line(unsigned char y, const char *s)
{
    unsigned char x = (80 - strlen(s) * 4) / 2;
    unsigned char r, j, f, b;
    const unsigned char *g;

    for (; *s; ++s, x += 4) {
        g = glyph(*s);
        for (r = 0; r < 8; ++r) {
            f = g[r];
            for (j = 0; j < 4; ++j, f <<= 2) {
                b = ((f & 0x80) ? 0xC0 : 0) | ((f & 0x40) ? 0x30 : 0);
                *scr(x + j, y + r * 2) = b;
                *scr(x + j, y + r * 2 + 1) = b;
            }
        }
    }
}

/* panel text, centred on text row `row`: pen 1 on pen 2, or (inverse) pen 2 on pen 3 */
static void panel_line(unsigned char row, const char *s, unsigned char inverse)
{
    unsigned char x = (80 - strlen(s) * 2) / 2;
    unsigned char r, f, n;

    for (; *s; ++s, x += 2) {
        for (r = 0; r < 8; ++r) {
            f = glyph(*s)[r];
            n = ~f;
            if (inverse) {
                *scr(x, row * 8 + r) = (n & 0xF0) | 0x0F;
                *scr(x + 1, row * 8 + r) = (n << 4) | 0x0F;
            } else {
                *scr(x, row * 8 + r) = (f & 0xF0) | (n >> 4);
                *scr(x + 1, row * 8 + r) = (f << 4) | (n & 0x0F);
            }
        }
    }
}

static void add(const char *s)
{
    while (*s && scroll_len < sizeof scroll_text)
        scroll_text[scroll_len++] = *s++;
}

/* the colours that stay: border black, pen 0 black - the panel rows' text colours */
static const unsigned char panel_ink[8] = { 0x4B, 0x4B, 0x4B, 0x4A, 0x59, 0x4B, 0x5B, 0x4B };

int main(void)
{
    unsigned int i;
    unsigned char *e;

    printf("Fetching the temperature in Celle\r\nthrough the M4...\r\n");
    fetch_temperature();

    fx_init();
    for (i = 80; i < 144; ++i)                  /* panel background: pen 2 */
        memset(scr(0, i), 0x0F, 80);

    big_line(8, "CPC 6128 + M4");
    strcpy(line, "CELLE ");
    strcat(line, temp);
    strcat(line, "*C");
    big_line(24, line);

    panel_line(11, "A small demo from the CPC devkit", 0);
    strcpy(line, "Celle right now: ");
    strcat(line, temp);
    strcat(line, " C");
    panel_line(13, line, 0);
    panel_line(14, "live via the M4, HTTP + JSON", 0);
    panel_line(16, "SDCC, lib/m4, RASM, CPCSyntaxError", 0);
    panel_line(17, " github.com/joergr72idb ", 1);

    for (i = 0; i <= 200; ++i) {
        e = fx_tbl + i * 4;
        e[0] = 0x10;                            /* border */
        e[1] = 0x54;                            /* black */
        e[2] = ((i >= 8 && i < 40) || (i >= 80 && i < 144) || (i >= 176 && i < 184)) ? 1 : 0;
        e[3] = (i >= 80 && i < 144) ? panel_ink[(i - 80) >> 3] : 0x54;
    }

    add("*** Hello from Celle! ***   The temperature here is ");
    add(temp);
    add(" C right now - the CPC fetched it itself through the M4 board "
        "(HTTP + JSON from open-meteo.com) ...   "
        "Code: SDCC (C + sdasz80 assembler) with the kit's lib/m4, tested in CPCSyntaxError "
        "with its M4 emulation ...   Music: three AY-3-8912 voices, drums and bass sharing one - "
        "raster bars and rainbows by changing the Gate Array colours on every scan line, "
        "counted to the microsecond ...   Get the whole toolchain: "
        "github.com/joergr72idb/development-kit-cpc-and-m4"
        " - kits for the Atari XL, the C64 and the Apple II too ...   "
        "More at github.com/joergr72idb: Retro Game Battle, Berlin Blues BBS, CPC Telnet, "
        "FujiNet Network CPC, Neon Grid ...   Greetings to the FujiNet team, the Atari-Club "
        "Celle and everyone at Classic Computing 2026 ...   Let's wrap!          ");

    fx_start();                                 /* never returns */
    return 0;
}
